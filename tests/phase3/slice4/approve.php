<?php
/** Proof — approve, reject (spec "Proof", 3): Marco approves both (the notices); self-approval refused; Dana (no right) → 403; an approved expense's money locked in words; a rejection with a reason returns it editable and resubmittable; a billed one is not rejected; an engagement he does not manage is not his to approve. */
require __DIR__ . '/lib.php';
[$acme, $beta] = expense_world();
$priya = as_member(26); $marco = as_member(27); $dana = as_member(30); $bea = as_member(28); $owner = as_member(1);
$e1 = (int) one("SELECT id FROM expenses WHERE number = 'EXP-000001'");
$e2 = (int) one("SELECT id FROM expenses WHERE description = 'SMOKE coffee'");
$e3 = (int) one("SELECT id FROM expenses WHERE description = 'SMOKE train'");
$e1 > 0 && $e2 > 0 && $e3 > 0 or exit(fwrite(STDERR, "run record.php first\n") ?: 2);

echo "1. Who may\n";
[$c, $b] = act($dana, '/expenses/approve.php', ['expense' => $e1]);
ok($c === 403 && msg($b) === 'You may not approve expenses.', 'Dana (a Consultant): 403 "You may not approve expenses."');
[$c, $b] = act($priya, '/expenses/approve.php', ['expense' => $e1]);
ok($c === 403, 'Priya may not approve her own: 403 (no expenses.approve)');
[$c, $d] = screen($marco, '/expenses/approvals');
$ids = array_column(array_column($d['expenses'], 'expense_id'), null);
ok($c === 200 && in_array($e1, $ids, true) && in_array($e2, $ids, true) && in_array($e3, $ids, true) && $d['expenses'][0]['status'] === 'submitted', 'Marco\'s approvals list: the submitted ones, oldest first');
ok($d['expenses'][0]['has_receipt'] === true || $d['expenses'][0]['receipt_needed'] === false, 'with the receipt flag');
[$c, $d2] = screen($marco, '/expenses/approvals?missing_receipt=1');
ok($c === 200 && !in_array($e1, array_column($d2['expenses'], 'expense_id'), true), 'the missing-receipt filter leaves out the one with its receipt');

echo "2. Approve\n";
$since = last_activity_id();
[$c, $b] = act($marco, '/expenses/approve.php', ['expense' => $e1]);
$x = expense_row($e1);
ok($c === 200 && $b['status'] === 'approved' && $b['billable_amount'] === '132.00' && $x['status'] === 'approved' && (int) $x['approved_by'] === 27 && $x['approved_at'] !== null, 'expense_approve: approved by Marco, billable amount 132.00');
$log = activity('expense.approve', $since);
$after = json_decode((string) $log[0]['after'], true);
ok(count($log) === 1 && (int) $log[0]['engagement_id'] === $acme && $after['amount'] === '120.00' && $after['currency'] === 'USD' && $after['billable_amount'] === '132.00' && $after['number'] === 'EXP-000001' && json_decode((string) $log[0]['before'], true)['status'] === 'submitted', 'expense.approve logged with engagement_id, amount, currency, billable_amount');
ok(q("SELECT member_id, record_type, record_id FROM notifications WHERE kind = 'expense_approved' ORDER BY id DESC LIMIT 1") === [['member_id' => 26, 'record_type' => 'expense', 'record_id' => $e1]], 'Priya is told it was approved');
[$c, $b] = act($marco, '/expenses/approve.php', ['expense' => $e2]);
ok($c === 200 && expense_row($e2)['status'] === 'approved', 'the coffee too (the company-card one)');
ok(str_contains((string) one("SELECT body FROM notifications WHERE kind = 'expense_approved' AND record_id = :e", ['e' => $e2]), 'company card'), 'and its notice says there is nothing to reimburse');
[$c, $b] = act($marco, '/expenses/approve.php', ['expense' => $e1]);
ok($c === 422 && msg($b) === 'Expense EXP-000001 is approved, not submitted', 'approving twice: the verb\'s words');
$since = last_activity_id();
[$c, $b] = record_expense($marco, $acme, '20.00', ['description' => 'SMOKE Marco own']);
$own = (int) $b['record_id'];
act($marco, '/expenses/submit.php', ['expense' => $own]);
[$c, $b] = act($marco, '/expenses/approve.php', ['expense' => $own]);
ok($c === 422 && msg($b) === 'Nobody approves their own expense', 'self-approval: 422 "Nobody approves their own expense"');
[$c, $b] = act($owner, '/expenses/approve.php', ['expense' => $own]);
ok($c === 200 && expense_row($own)['status'] === 'approved' && (int) expense_row($own)['approved_by'] === 1, 'the super-admin approves it (the verb\'s one exception)');
ok((int) one("SELECT count(*) FROM notifications WHERE kind = 'expense_approved' AND record_id = :e AND member_id = 27", ['e' => $own]) === 1, 'Marco is told (it is his expense)');

echo "3. Locked once approved or submitted — in words\n";
[$c, $b] = act($priya, '/expenses/save.php', ['expense' => $e1, 'amount' => '130.00']);
ok($c === 422 && msg($b) === 'Expense EXP-000001 is approved and locked; reject it first, or credit the invoice', 'an approved expense\'s amount: the trigger\'s words (' . msg($b) . ')');
[$c, $b] = act($priya, '/expenses/delete.php', ['expense' => $e1]);
ok($c === 422 && msg($b) === 'Expense EXP-000001 is approved and is never deleted', 'its delete: the trigger\'s words');
$r = page($priya, '/expenses/' . $e1 . '/edit');
ok($r['code'] === 422 && str_contains($r['body'], 'This expense is approved'), 'the edit page for an approved expense: 422 in words');
[$c, $b] = act($priya, '/expenses/save.php', ['expense' => $e3, 'amount' => '95.00']);
ok($c === 422 && str_contains(msg($b), 'is submitted; ask for it back (reject) to change it'), 'a submitted expense\'s amount: "ask for it back (reject)" (' . msg($b) . ')');
[$c, $d] = screen($marco, '/expenses/' . $e1);
ok($c === 200 && $d['may']['approve'] === false && $d['may']['reject'] === true && $d['may']['reimburse'] === false && $d['may']['edit'] === false, 'Marco\'s view of the approved one: Send back allowed, no Approve, no edit, no reimburse (not billing)');

echo "4. Reject: the reason, then editable\n";
[$c, $b] = act($marco, '/expenses/reject.php', ['expense' => $e3]);
ok($c === 422 && isset(fields($b)['reason']), 'reject without a reason: 422 (field reason)');
$since = last_activity_id();
[$c, $b] = act($marco, '/expenses/reject.php', ['expense' => $e3, 'reason' => 'SMOKE the amount is the gross fare, split it']);
$x = expense_row($e3);
ok($c === 200 && $x['status'] === 'rejected' && $x['rejection_reason'] === 'SMOKE the amount is the gross fare, split it' && (int) $x['rejected_by'] === 27, 'expense_reject: rejected with the reason');
$log = activity('expense.reject', $since);
ok(count($log) === 1 && json_decode((string) $log[0]['after'], true)['reason'] === 'SMOKE the amount is the gross fare, split it' && json_decode((string) $log[0]['after'], true)['amount'] === '90.00' && (int) $log[0]['engagement_id'] === $beta, 'expense.reject logged with the reason, the amount and the engagement');
$n = q("SELECT member_id, body FROM notifications WHERE kind = 'expense_rejected' ORDER BY id DESC LIMIT 1")[0];
ok($n['member_id'] === 26 && $n['body'] === 'SMOKE the amount is the gross fare, split it', 'Priya is told with the reason');
[$c, $d] = screen($priya, '/expenses/' . $e3 . '/edit');
ok($c === 200 && $d['expense']['status'] === 'rejected' && $d['expense']['rejection_reason'] !== null, 'the rejected expense opens for editing, with the reason');
[$c, $b] = act($priya, '/expenses/save.php', ['expense' => $e3, 'amount' => '85.00', 'submit' => '1']);
$x = expense_row($e3);
ok($c === 200 && $x['status'] === 'submitted' && $x['amount'] === '85.00' && $x['rejection_reason'] === null && $x['rejected_at'] === null, 'she changes it to 85.00 and Save-and-submits: submitted again, the rejection cleared');
[$c, $b] = act($marco, '/expenses/approve.php', ['expense' => $e3]);
ok($c === 200, 'and it is approved');
$since = last_activity_id();
[$c, $b] = act($marco, '/expenses/reject.php', ['expense' => $e3, 'reason' => 'SMOKE sent back after approval']);
ok($c === 200 && expense_row($e3)['status'] === 'rejected', 'rejecting an approved expense is allowed until it is billed or reimbursed');
[$c, $b] = act($priya, '/expenses/delete.php', ['expense' => $e3]);
ok($c === 200, 'a rejected expense may be deleted by its person');

echo "5. Billed and reimbursed ones are not sent back\n";
[$c, $b] = record_expense($priya, $acme, '50.00', ['description' => 'SMOKE to bill']);
$bill = (int) $b['record_id'];
act($priya, '/expenses/submit.php', ['expense' => $bill]);
act($marco, '/expenses/approve.php', ['expense' => $bill]);
$inv = (int) one("INSERT INTO invoices (client_id, engagement_id, due_date, currency, created_by) VALUES ((SELECT client_id FROM engagements WHERE id = :e), :e2, current_date + 30, 'USD', 1) RETURNING id", ['e' => $acme, 'e2' => $acme]);
$line = (int) one("INSERT INTO invoice_lines (invoice_id, kind, description, unit_price) VALUES (:i, 'expense', 'SMOKE expense', 55) RETURNING id", ['i' => $inv]);
q('INSERT INTO invoice_line_items (invoice_id, line_id, expense_id, amount) VALUES (:i, :l, :e, 55)', ['i' => $inv, 'l' => $line, 'e' => $bill]);
[$c, $d] = screen($marco, '/expenses/' . $bill);
ok($c === 200 && $d['expense']['billed'] === true && $d['may']['reject'] === false, 'a billed expense shows Billed and offers no Send back (slice 6\'s fixture: an invoice line item by SQL)');
[$c, $b] = act($marco, '/expenses/reject.php', ['expense' => $bill, 'reason' => 'SMOKE too late']);
ok($c === 422 && msg($b) === 'Expense EXP-' . substr((string) one('SELECT number FROM expenses WHERE id = :e', ['e' => $bill]), 4) . ' is billed or reimbursed; credit the invoice instead', 'rejecting a billed one: the verb\'s words (' . msg($b) . ')');
$body = page($priya, '/expenses/')['body'];
ok(str_contains($body, 'id="expense-card-' . $bill . '-billed"'), 'the card shows the Billed chip');
[$c, $b] = act($priya, '/expenses/save.php', ['expense' => $bill, 'amount' => '60.00']);
ok($c === 422 && str_contains(msg($b), 'is approved and locked'), 'and its money stays locked');

echo "6. An engagement he does not manage\n";
[$c, $b] = act($bea, '/engagements/save.php', ['client' => (int) one("SELECT id FROM clients WHERE name = 'SMOKE Beta'"), 'name' => 'SMOKE Beas expense eng', 'kind' => 'time_and_materials', 'start_date' => '2026-01-05', 'manager' => 28, 'start_now' => 'yes']);
$beas = (int) $b['record_id'];
act($bea, '/engagements/staffing/save.php', ['engagement' => $beas, 'member' => 26, 'role' => role('consultant'), 'valid_from' => '2026-01-05']);
[$c, $b] = record_expense($priya, $beas, '25.00', ['description' => 'SMOKE on Bea\'s engagement']);
$on = (int) $b['record_id'];
act($priya, '/expenses/submit.php', ['expense' => $on]);
[$c, $b] = act($marco, '/expenses/approve.php', ['expense' => $on]);
ok(in_array($c, [403, 404], true), 'Marco approving an expense on an engagement he does not manage: refused (' . $c . ' ' . msg($b) . ')');
[$c, $d] = screen($marco, '/expenses/approvals');
ok(!in_array($on, array_column($d['expenses'], 'expense_id'), true), 'it is not on his approvals list');
[$c, $b] = act(as_member(29), '/expenses/approve.php', ['expense' => $on]);
ok($c === 403 && msg($b) === 'You may not approve expenses.', 'Ann (Finance reads, never approves): 403');
[$c, $b] = act($bea, '/expenses/approve.php', ['expense' => $on]);
ok($c === 200 && (int) expense_row($on)['approved_by'] === 28, 'Bea, the engagement\'s own manager, approves it (expenses.approve + manages it)');
finish();
